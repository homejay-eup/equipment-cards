const isLive = process.argv.includes('--live')

async function main() {
  console.log(`共 ${ITEMS.length} 筆待匯入品項`)
  const byCategory = ITEMS.reduce((acc, i) => { acc[i.category] = (acc[i.category] || 0) + 1; return acc }, {})
  console.log('各分類筆數：', byCategory)

  if (!isLive) {
    console.log('\n[Dry-run] 未寫入資料庫。前 5 筆預覽：')
    console.log(ITEMS.slice(0, 5))
    console.log('\n確認無誤後執行： node _開發檔案/scripts/import-quote-items.js --live')
    return
  }

  const res = await fetch(`${SUPABASE_URL}/rest/v1/quote_items`, {
    method: 'POST',
    headers: {
      apikey: SERVICE_ROLE_KEY,
      Authorization: `Bearer ${SERVICE_ROLE_KEY}`,
      'Content-Type': 'application/json',
      Prefer: 'return=representation',
    },
    body: JSON.stringify(ITEMS),
  })

  if (!res.ok) {
    console.error('匯入失敗：', res.status, await res.text())
    process.exit(1)
  }
  const inserted = await res.json()
  console.log(`✓ 成功寫入 ${inserted.length} 筆`)
}

main()
